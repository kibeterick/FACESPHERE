    def get_inbox(self, unread_only: bool = False) -> List[Dict]:
        """Get inbox emails"""
        if unread_only:
            return [email for email in self.inbox if not email['read']]
        return self.inbox
    
    def get_sent_emails(self, limit: int = 50) -> List[Dict]:
        """Get sent emails"""
        return self.sent_emails[-limit:]
    
    def mark_as_read(self, email_id: int) -> bool:
        """Mark email as read"""
        for email in self.inbox:
            if email['id'] == email_id:
                email['read'] = True
                return True
        return False
    
    def mark_as_unread(self, email_id: int) -> bool:
        """Mark email as unread"""
        for email in self.inbox:
            if email['id'] == email_id:
                email['read'] = False
                return True
        return False
    
    def star_email(self, email_id: int) -> bool:
        """Star an email"""
        for email in self.inbox:
            if email['id'] == email_id:
                email['starred'] = not email.get('starred', False)
                return True
        return False
    
    def delete_email(self, email_id: int) -> bool:
        """Delete an email"""
        self.inbox = [email for email in self.inbox if email['id'] != email_id]
        return True
    
    def search_emails(self, query: str, folder: str = 'all') -> List[Dict]:
        """Search emails"""
        query_lower = query.lower()
        results = []
        
        search_list = self.inbox if folder == 'INBOX' else self.inbox + self.sent_emails
        
        for email in search_list:
            if (query_lower in email['subject'].lower() or 
                query_lower in email['body'].lower() or
                query_lower in email.get('from', '').lower()):
                results.append(email)
        
        return results
    
    def create_draft(self, to_email: str, subject: str, body: str) -> Dict:
        """Create email draft"""
        draft = {
            'id': len(self.drafts) + 1,
            'to': to_email,
            'subject': subject,
            'body': body,
            'created_at': datetime.now().isoformat(),
            'updated_at': datetime.now().isoformat()
        }
        
        self.drafts.append(draft)
        
        return draft
    
    def get_drafts(self) -> List[Dict]:
        """Get all drafts"""
        return self.drafts
    
    def send_draft(self, draft_id: int) -> Dict:
        """Send a draft email"""
        for draft in self.drafts:
            if draft['id'] == draft_id:
                result = self.send_email(draft['to'], draft['subject'], draft['body'])
                if result['success']:
                    self.drafts.remove(draft)
                return result
        
        return {'success': False, 'message': 'Draft not found'}
    
    def get_email_statistics(self) -> Dict:
        """Get email statistics"""
        total_inbox = len(self.inbox)
        unread_count = len([e for e in self.inbox if not e['read']])
        starred_count = len([e for e in self.inbox if e.get('starred', False)])
        total_sent = len(self.sent_emails)
        total_drafts = len(self.drafts)
        
        return {
            'inbox': {
                'total': total_inbox,
                'unread': unread_count,
                'starred': starred_count
            },
            'sent': total_sent,
            'drafts': total_drafts,
            'total_emails': total_inbox + total_sent
        }
    
    def add_template(self, name: str, subject: str, body: str) -> bool:
        """Add custom email template"""
        self.templates[name] = {
            'subject': subject,
            'body': body
        }
        return True
    
    def get_templates(self) -> Dict:
        """Get all email templates"""
        return self.templates
    
    def send_bulk_email(self, recipients: List[str], subject: str, 
                       body: str, personalize: bool = False) -> Dict:
        """Send bulk emails"""
        results = {
            'success': 0,
            'failed': 0,
            'total': len(recipients)
        }
        
        for recipient in recipients:
            result = self.send_email(recipient, subject, body)
            if result['success']:
                results['success'] += 1
            else:
                results['failed'] += 1
        
        return results


