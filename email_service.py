    def send_email(self, to_email: str, subject: str, body: str, 
                   html: bool = False, attachments: List[str] = None) -> Dict:
        """Send an email via Gmail SMTP"""
        try:
            # Create message
            msg = MIMEMultipart('alternative')
            msg['From'] = self.email_address
            msg['To'] = to_email
            msg['Subject'] = subject
            msg['Date'] = email.utils.formatdate(localtime=True)
            
            # Add body
            if html:
                msg.attach(MIMEText(body, 'html'))
            else:
                msg.attach(MIMEText(body, 'plain'))
            
            # Add attachments
            if attachments:
                for file_path in attachments:
                    if os.path.exists(file_path):
                        with open(file_path, 'rb') as f:
                            part = MIMEBase('application', 'octet-stream')
                            part.set_payload(f.read())
                            encoders.encode_base64(part)
                            part.add_header('Content-Disposition', 
                                          f'attachment; filename={os.path.basename(file_path)}')
                            msg.attach(part)
            
            # Try to send via real SMTP
            try:
                # Connect to Gmail SMTP server
                server = smtplib.SMTP(self.smtp_server, self.smtp_port)
                server.starttls()  # Enable TLS encryption
                
                # Login to Gmail
                server.login(self.email_address, self.email_password)
                
                # Send email
                server.send_message(msg)
                server.quit()
                
                print(f"✅ Email sent successfully to {to_email}")
                print(f"   Subject: {subject}")
                
                # Log sent email
                sent_email = {
                    'id': len(self.sent_emails) + 1,
                    'to': to_email,
                    'subject': subject,
                    'body': body,
                    'timestamp': datetime.now().isoformat(),
                    'status': 'sent',
                    'attachments': attachments or []
                }
                self.sent_emails.append(sent_email)
                
                return {
                    'success': True,
                    'message': 'Email sent successfully via Gmail',
                    'email_id': sent_email['id']
                }
                
            except smtplib.SMTPAuthenticationError:
                print("⚠️  Gmail authentication failed. Using simulation mode.")
                print("   To send real emails, configure EMAIL_ADDRESS and EMAIL_PASSWORD in .env")
                print("   For Gmail, use an App Password: https://myaccount.google.com/apppasswords")
                
                # Fall back to simulation
                print(f"📧 Email simulated to {to_email}")
                print(f"   Subject: {subject}")
                
                sent_email = {
                    'id': len(self.sent_emails) + 1,
                    'to': to_email,
                    'subject': subject,
                    'body': body,
                    'timestamp': datetime.now().isoformat(),
                    'status': 'simulated',
                    'attachments': attachments or []
                }
                self.sent_emails.append(sent_email)
                
                return {
                    'success': True,
                    'message': 'Email simulated (configure Gmail credentials for real sending)',
                    'email_id': sent_email['id']
                }
            
        except Exception as e:
            print(f"❌ Email error: {e}")
            return {
                'success': False,
                'message': str(e)
            }
    
    def send_from_template(self, template_name: str, to_email: str, 
                          variables: Dict) -> Dict:
        """Send email using a template"""
        if template_name not in self.templates:
            return {
                'success': False,
                'message': f'Template {template_name} not found'
            }
        
        template = self.templates[template_name]
        
        # Format subject and body with variables
        subject = template['subject'].format(**variables)
        body = template['body'].format(**variables)
        
        return self.send_email(to_email, subject, body)
    
